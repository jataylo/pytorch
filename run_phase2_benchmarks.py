#!/usr/bin/env python3
"""run_phase2_benchmarks.py — Benchmark every compiled kernel under multiple modes.

Phase 1 runs benchmark_pointwise.py once with autotune (no heuristics) and
TORCHINDUCTOR_BENCHMARK_KERNEL=1, producing kernel .py files with a standalone
benchmark harness (get_args / call / __main__).

Phase 2 (this script) runs each kernel file N times, once per mode:

  autotune        HEURISTICS=0  — reads Phase-1 disk cache  → no re-autotuning
  no_tune         HEURISTICS=0  — patches max_autotune=False → single default config
  h3_wpeu_div     HEURISTICS=1 WPEU=1 DIV=1   × TOP_N sweep (1, 5, 10)
  h4_nowpeu_div   HEURISTICS=1 WPEU=0 DIV=1   × TOP_N sweep
  h5_wpeu_nodiv   HEURISTICS=1 WPEU=1 DIV=0   × TOP_N sweep
  h6_nowpeu_nodiv HEURISTICS=1 WPEU=0 DIV=0   × TOP_N sweep

Before running each file the script applies two patches to a temp copy:
  1. device=hip / device=cuda → device='cuda:0'
     (old codegen bug: embeds device type without quotes)
  2. For no_tune mode: 'max_autotune': True → 'max_autotune': False
     (forces the single-default-config path in inductor)

The autotune cache key is hash(config_list) — autotune and heuristic modes write
to different slots in the SAME cache dir, so they never collide.  Autotune reads
its Phase-1 entry instantly; heuristic modes do a fresh mini-autotune of top-N
configs in an isolated subprocess.

--distributed spawns one worker per GPU (ROCR_VISIBLE_DEVICES=N), benchmarking
different kernels in parallel.  Modes for a single kernel are always sequential.

Output JSONL (--out): one record per kernel × mode.
  kernel_name, kernel_file, kernel_type, mode_label, timing_ms, gb_per_s, num_gb, rc

Usage:
    python run_phase2_benchmarks.py  \\
        --cache-dir  <Phase-1 TORCHINDUCTOR_CACHE_DIR>  \\
        --out        phase2_timings.jsonl  \\
        [--top-n "1 5 10"]          TOP_N values for heuristic modes
        [--rep N]                   triton do_bench reps (default: 100)
        [--timeout S]               per-kernel per-mode timeout (default: 180)
        [--distributed]             use all GPUs in parallel
        [--gpus N]                  override GPU count (default: auto-detect)
        [--verbose]                 print full stdout/stderr for every run
"""

import argparse
import json
import os
import queue
import re
import subprocess
import sys
import threading
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path


# ---------------------------------------------------------------------------
# Kernel file discovery
# ---------------------------------------------------------------------------

_HARNESS_MARKERS = ("def get_args():", "if __name__ == '__main__':", "triton_heuristics.")
# fxgraph / aotautograd compiled-module files have get_args() too but use
# compiled_module_main — exclude them.
_EXCLUDE_MARKERS = ("compiled_module_main",)
_FN_RE    = re.compile(r"^def (triton_(?:poi|red|per|combo)_\S+)\(", re.MULTILINE)
_TYPE_MAP = {
    "pointwise":             "pointwise",
    "reduction":             "reduction",
    "persistent_reduction":  "persistent_reduction",
    "cooperative_reduction": "reduction",
}


def find_kernel_files(cache_dir: Path) -> list[Path]:
    """All .py files that have the BENCHMARK_KERNEL=1 triton-kernel harness."""
    out = []
    for f in sorted(cache_dir.rglob("*.py")):
        try:
            text = f.read_text(errors="replace")
            if (all(m in text for m in _HARNESS_MARKERS)
                    and not any(m in text for m in _EXCLUDE_MARKERS)):
                out.append(f)
        except OSError:
            pass
    return out


def kernel_info(text: str, fallback: str) -> tuple[str, str]:
    m = _FN_RE.search(text)
    name = m.group(1) if m else fallback
    ktype = "other"
    for dec, label in _TYPE_MAP.items():
        if f"triton_heuristics.{dec}(" in text:
            ktype = label
            break
    return name, ktype


# ---------------------------------------------------------------------------
# File patching
# ---------------------------------------------------------------------------

# Old codegen bug: device type embedded without string quotes → NameError.
# New codegen emits device='cuda:0' (quoted), so new files pass through.
_DEVICE_RE = re.compile(r"\bdevice=(hip|cuda)\b")


def patch_kernel_file(text: str, no_tune: bool = False) -> str:
    """Apply patches to kernel source before running standalone."""
    # 1. Fix device= NameError in files generated by old codegen
    text = _DEVICE_RE.sub("device='cuda:0'", text)

    # 2. no_tune mode: force max_autotune=False so inductor takes the
    #    single-default-config path instead of the multi-config autotune path.
    if no_tune:
        text = text.replace("'max_autotune': True", "'max_autotune': False")
        text = text.replace('"max_autotune": True', '"max_autotune": False')

    return text


# ---------------------------------------------------------------------------
# Mode definitions
# ---------------------------------------------------------------------------

_BASE_MODES: list[tuple[str, dict, bool]] = [
    ("autotune", {
        "TORCHINDUCTOR_POINTWISE_HEURISTICS": "0",
    }, False),
    ("no_tune", {
        "TORCHINDUCTOR_POINTWISE_HEURISTICS": "0",
    }, True),   # patches max_autotune=False → single default config
]

_H_VARIANTS = [
    ("h3_wpeu_div",     {"TORCHINDUCTOR_POINTWISE_WAVES_PER_EU": "1",
                         "TORCHINDUCTOR_HEURISTICS_DIVERSITY": "1"}),
    ("h4_nowpeu_div",   {"TORCHINDUCTOR_POINTWISE_WAVES_PER_EU": "0",
                         "TORCHINDUCTOR_HEURISTICS_DIVERSITY": "1"}),
    ("h5_wpeu_nodiv",   {"TORCHINDUCTOR_POINTWISE_WAVES_PER_EU": "1",
                         "TORCHINDUCTOR_HEURISTICS_DIVERSITY": "0"}),
    ("h6_nowpeu_nodiv", {"TORCHINDUCTOR_POINTWISE_WAVES_PER_EU": "0",
                         "TORCHINDUCTOR_HEURISTICS_DIVERSITY": "0"}),
]

_H_BASE_ENV = {
    "TORCHINDUCTOR_POINTWISE_HEURISTICS": "1",
    "TORCHINDUCTOR_HEURISTICS_REAL_BENCH": "0",
}


def build_modes(top_n_values: list[int]) -> list[tuple[str, dict, bool]]:
    modes = list(_BASE_MODES)
    for variant_name, variant_env in _H_VARIANTS:
        for n in top_n_values:
            label = f"{variant_name}_n{n}"
            env = {**_H_BASE_ENV, **variant_env, "TORCHINDUCTOR_HEURISTICS_TOP_N": str(n)}
            modes.append((label, env, False))
    return modes


# ---------------------------------------------------------------------------
# GPU detection + platform
# ---------------------------------------------------------------------------

# Set by main() based on platform detection; used in run_kernel.
_GPU_ENV_VAR: str = "CUDA_VISIBLE_DEVICES"
# Complementary env var to CLEAR in subprocesses (avoids ROCm/CUDA conflicts).
_GPU_ENV_VAR_CLEAR: str = "ROCR_VISIBLE_DEVICES"


def detect_platform() -> tuple[int, str, str]:
    """Return (n_gpus, gpu_env_var, gpu_env_var_to_clear)."""
    try:
        r = subprocess.run(
            [sys.executable, "-c",
             "import torch; "
             "print(torch.cuda.device_count()); "
             "print('rocm' if torch.version.hip else 'cuda')"],
            capture_output=True, text=True, timeout=30,
        )
        lines = r.stdout.strip().splitlines()
        n        = int(lines[0]) if lines else 1
        platform = lines[1].strip() if len(lines) > 1 else "cuda"
    except Exception:
        n, platform = 1, "cuda"

    if platform == "rocm":
        return max(1, n), "ROCR_VISIBLE_DEVICES", "CUDA_VISIBLE_DEVICES"
    else:
        return max(1, n), "CUDA_VISIBLE_DEVICES", "ROCR_VISIBLE_DEVICES"


# ---------------------------------------------------------------------------
# .best_config cleanup
# ---------------------------------------------------------------------------

def clear_best_configs(kernel_file: Path) -> None:
    """Remove .best_config files in the kernel's own cache subdirectory."""
    for p in kernel_file.parent.glob("*.best_config"):
        try:
            p.unlink()
        except OSError:
            pass


# ---------------------------------------------------------------------------
# Subprocess runner
# ---------------------------------------------------------------------------

_TIMING_RE = re.compile(r"([\d.]+)\s*ms\s+([\d.]+)\s*GB\s+([\d.]+)\s*GB/s")


def run_kernel(
    patched_file: Path,
    cache_dir: str,
    extra_env: dict,
    rep: int,
    timeout: int,
    gpu_idx: int | None,
    verbose: bool,
) -> tuple[float | None, float | None, float | None, int, str]:
    """Run `python <patched_file>` and return (ms, num_gb, gb_per_s, rc, err)."""
    env = os.environ.copy()
    env["TORCHINDUCTOR_CACHE_DIR"] = cache_dir
    env["TORCHINDUCTOR_BENCHMARK_KERNEL"] = "1"
    env.pop("TORCHINDUCTOR_HEURISTICS_VERBOSE", None)
    env.pop("_INDUCTOR_KERNEL_LOG_FILE", None)
    env.pop("_BENCH_MODE_LABEL", None)
    if gpu_idx is not None:
        # Clear the conflicting GPU-visibility variable first, then set the
        # platform-correct one.  On ROCm, setting CUDA_VISIBLE_DEVICES causes
        # "Could not find an active GPU backend"; on CUDA the reverse is true.
        env.pop(_GPU_ENV_VAR_CLEAR, None)
        env[_GPU_ENV_VAR] = str(gpu_idx)
    env.update(extra_env)

    try:
        r = subprocess.run(
            [sys.executable, str(patched_file)],
            env=env,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        stdout = r.stdout
        stderr = r.stderr

        if verbose:
            with _print_lock:
                if stdout:
                    print(stdout, end="")
                if stderr:
                    print(stderr, end="", file=sys.stderr)

        m = _TIMING_RE.search(stdout)
        if m:
            return float(m.group(1)), float(m.group(2)), float(m.group(3)), r.returncode, ""
        err = (stderr or stdout or "no timing output")[:400]
        return None, None, None, r.returncode, err
    except subprocess.TimeoutExpired:
        return None, None, None, -1, f"TIMEOUT >{timeout}s"
    except Exception as exc:
        return None, None, None, -2, str(exc)[:400]


# ---------------------------------------------------------------------------
# Per-kernel worker (all modes, one GPU)
# ---------------------------------------------------------------------------

_print_lock = threading.Lock()


_PID_TAG = str(os.getpid())


def process_kernel(
    kfile: Path,
    cache_dir: str,
    modes: list[tuple[str, dict, bool]],
    rep: int,
    timeout: int,
    gpu_idx: int | None,
    verbose: bool,
    progress_prefix: str,
) -> list[dict]:
    """Run all modes for one kernel file. Returns list of JSONL records."""
    raw_text = kfile.read_text(errors="replace")
    kname, ktype = kernel_info(raw_text, kfile.stem)

    # Write patched copies alongside the original in the cache subdir.
    # Using PID in the name avoids clashes if two runs overlap.
    # Keeping files in the cache dir (not /tmp) ensures subprocess visibility.
    stem = kfile.stem
    patched_normal = kfile.parent / f"{stem}_p2n_{_PID_TAG}.py"
    patched_notune = kfile.parent / f"{stem}_p2t_{_PID_TAG}.py"
    try:
        patched_normal.write_text(patch_kernel_file(raw_text, no_tune=False))
        patched_notune.write_text(patch_kernel_file(raw_text, no_tune=True))
    except OSError as exc:
        return [{"kernel_name": kname, "kernel_file": str(kfile),
                 "kernel_type": ktype, "mode_label": "SETUP_ERROR",
                 "timing_ms": None, "gb_per_s": None, "num_gb": None,
                 "rc": -3, "error": str(exc)}]

    # Clear .best_config before starting this kernel's mode sweep
    clear_best_configs(kfile)

    records = []
    try:
        for mode_label, mode_env, is_no_tune in modes:
            src = patched_notune if is_no_tune else patched_normal
            gpu_tag = f" [GPU {gpu_idx}]" if gpu_idx is not None else ""

            with _print_lock:
                print(f"  {progress_prefix} {mode_label:<30} {kname[:38]:<38}{gpu_tag} ... ",
                      end="", flush=True)

            if verbose:
                with _print_lock:
                    print()  # newline before verbose output

            ms, ngb, gbs, rc, err = run_kernel(
                src, cache_dir, mode_env, rep, timeout, gpu_idx, verbose,
            )

            if rc == -1:
                status = "TIMEOUT"
            elif ms is None:
                status = f"FAIL rc={rc}  {err[:60]}"
            else:
                status = f"{ms:.3f}ms  {gbs:.1f}GB/s"

            with _print_lock:
                print(status)

            rec: dict = {
                "kernel_name": kname,
                "kernel_file": str(kfile),
                "kernel_type": ktype,
                "mode_label":  mode_label,
                "timing_ms":   ms,
                "gb_per_s":    gbs,
                "num_gb":      ngb,
                "rc":          rc,
            }
            if err:
                rec["error"] = err
            records.append(rec)
    finally:
        # Remove patched copies from the cache dir
        for p in (patched_normal, patched_notune):
            try:
                p.unlink(missing_ok=True)
            except OSError:
                pass

    return records


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache-dir",   required=True,
                    help="TORCHINDUCTOR_CACHE_DIR from Phase 1")
    ap.add_argument("--out",         required=True,
                    help="Output JSONL path")
    ap.add_argument("--top-n",       default="1 5 10",
                    help="Space-separated TOP_N values (default: '1 5 10')")
    ap.add_argument("--rep",         type=int, default=100,
                    help="triton do_bench reps (default: 100)")
    ap.add_argument("--timeout",     type=int, default=180,
                    help="Per-kernel per-mode timeout in seconds (default: 180)")
    ap.add_argument("--distributed", action="store_true",
                    help="Benchmark kernels in parallel across all GPUs")
    ap.add_argument("--gpus",        type=int, default=0,
                    help="Number of GPUs (default: auto-detect)")
    ap.add_argument("--verbose",     action="store_true",
                    help="Print full stdout/stderr for every subprocess run")
    args = ap.parse_args()

    global _GPU_ENV_VAR, _GPU_ENV_VAR_CLEAR

    top_n_values = [int(x) for x in args.top_n.split()]
    modes        = build_modes(top_n_values)
    cache_dir    = args.cache_dir

    detected_gpus, _GPU_ENV_VAR, _GPU_ENV_VAR_CLEAR = detect_platform()
    n_gpus = args.gpus if args.gpus > 0 else detected_gpus
    if not args.distributed:
        n_gpus = 1  # serial: no per-GPU isolation override

    print(f"\n{'='*72}")
    print(f"Phase 2: standalone kernel benchmarks")
    print(f"  Cache dir   : {cache_dir}")
    print(f"  TOP_N       : {top_n_values}")
    print(f"  rep         : {args.rep}")
    print(f"  platform    : {_GPU_ENV_VAR} (clears {_GPU_ENV_VAR_CLEAR})")
    print(f"  distributed : {args.distributed} ({n_gpus} GPU(s))")
    print(f"  verbose     : {args.verbose}")
    print(f"  Modes ({len(modes)}): {[m[0] for m in modes]}")
    print(f"{'='*72}\n")

    cache_path   = Path(cache_dir)
    kernel_files = find_kernel_files(cache_path)
    print(f"Found {len(kernel_files)} kernel files with benchmark harness")

    if not kernel_files:
        print("ERROR: No kernel files found.  Did Phase 1 run with "
              "TORCHINDUCTOR_BENCHMARK_KERNEL=1?", file=sys.stderr)
        sys.exit(1)

    total_runs = len(kernel_files) * len(modes)
    print(f"Total runs  : {total_runs}  "
          f"({len(kernel_files)} kernels × {len(modes)} modes)\n")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    n_ok = n_fail = 0
    kernel_idx = 0
    write_lock = threading.Lock()

    with open(out_path, "w") as out_f:

        def submit_kernel(kfile: Path, gpu_idx: int | None) -> list[dict]:
            nonlocal kernel_idx
            with _print_lock:
                kernel_idx += 1
                prefix = f"[{kernel_idx:3d}/{len(kernel_files)}]"
            return process_kernel(
                kfile, cache_dir, modes,
                args.rep, args.timeout, gpu_idx, args.verbose, prefix,
            )

        if args.distributed and n_gpus > 1:
            # Build a GPU-slot pool: cycle GPU indices across workers
            gpu_queue: queue.Queue = queue.Queue()
            for g in range(n_gpus):
                gpu_queue.put(g)

            def submit_with_gpu(kfile: Path) -> list[dict]:
                gpu = gpu_queue.get()
                try:
                    return submit_kernel(kfile, gpu)
                finally:
                    gpu_queue.put(gpu)

            with ThreadPoolExecutor(max_workers=n_gpus) as pool:
                futures = {pool.submit(submit_with_gpu, kf): kf
                           for kf in kernel_files}
                for fut in as_completed(futures):
                    try:
                        records = fut.result()
                    except Exception as exc:
                        kf = futures[fut]
                        print(f"  ERROR processing {kf.stem}: {exc}")
                        records = []
                    with write_lock:
                        for rec in records:
                            out_f.write(json.dumps(rec) + "\n")
                            out_f.flush()
                            if rec["timing_ms"] is not None:
                                n_ok += 1
                            else:
                                n_fail += 1
        else:
            # Serial: one kernel at a time, no ROCR_VISIBLE_DEVICES override
            for kfile in kernel_files:
                records = submit_kernel(kfile, gpu_idx=None)
                for rec in records:
                    out_f.write(json.dumps(rec) + "\n")
                    out_f.flush()
                    if rec["timing_ms"] is not None:
                        n_ok += 1
                    else:
                        n_fail += 1

    print(f"\n{'='*72}")
    print(f"Done: {n_ok} OK  {n_fail} FAIL")
    print(f"JSONL → {out_path}")
    if n_ok == 0:
        print("ERROR: all kernel runs failed.", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
